/** Build short cached menu clips, never full gameplay audio.
 * pnpm exec tsx scripts/fusemania-previews.ts [--source-cache /path/to/staged-media]
 * Upload artifacts/fusemania-previews/ to the public media bucket afterwards.
 */
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, extname, join } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { SONGS } from "./lib/fusemania/songs.js";
import { SONGS_DATA } from "../games/fusemania/src/engine/songs-data.js";
import { parseSimfile } from "../games/fusemania/src/engine/simfile.js";
import { PREVIEW_CLIPS } from "../games/fusemania/src/app/previews-data.js";

process.chdir(fileURLToPath(new URL("..", import.meta.url)));
const args = process.argv.slice(2);
if (args.includes("--aliases-only")) {
  const clips = SONGS.map((song) => {
    const source = SONGS.find((s) => s.id === (song.previewOf ?? song.id));
    if (!source || source.audio !== song.audio)
      throw Error(`${song.id}: preview source audio differs`);
    const clip = PREVIEW_CLIPS.find((c) => c.id === source.id);
    if (!clip) throw Error(`${song.id}: no immutable source preview`);
    return { ...clip, id: song.id };
  });
  writeFileSync(
    "games/fusemania/src/app/previews-data.ts",
    await format(
      `// Generated by scripts/fusemania-previews.ts. Audio lives in the public GCS media bucket, never Git.\nexport const PREVIEW_CLIPS = ${JSON.stringify(clips)} as const;\n`,
      { parser: "typescript" },
    ),
  );
  console.log(
    `Reused immutable source clips for ${clips.length} songs; no audio generated or uploaded.`,
  );
  process.exit(0);
}
const cacheAt = args.indexOf("--source-cache");
const sourceCache = cacheAt >= 0 ? args[cacheAt + 1] : undefined;
if (cacheAt >= 0 && !sourceCache)
  throw new Error("--source-cache needs a directory");
const bucket = "andershaf-87-fuse-media";
const staged = "artifacts/fusemania-previews";
const downloadCache = "artifacts/fusemania-preview-sources";
mkdirSync(downloadCache, { recursive: true });
const clips: {
  id: string;
  url: string;
  bytes: number;
  sha256: string;
  start: number;
  audibleSeconds: number;
  silenceSeconds: number;
}[] = [];
for (const song of SONGS) {
  if (song.previewOf) {
    const source = SONGS.find((s) => s.id === song.previewOf),
      clip = clips.find((c) => c.id === song.previewOf);
    if (!source || !clip || source.audio !== song.audio)
      throw Error(`${song.id}: invalid preview alias`);
    clips.push({ ...clip, id: song.id });
    continue;
  }
  const data = SONGS_DATA.find((entry) => entry.id === song.id);
  if (!data) throw new Error(`${song.id}: missing bundled simfile`);
  let source = song.file;
  if (!source) {
    const url = new URL(song.audio);
    const object = decodeURIComponent(url.pathname).replace(`/${bucket}/`, "");
    const existing =
      sourceCache && url.hostname === "storage.googleapis.com"
        ? join(sourceCache, object)
        : undefined;
    const cached = join(
      downloadCache,
      `${song.audioIntegrity?.sha256 ?? song.id}${extname(url.pathname)}`,
    );
    if (existing && existsSync(existing)) source = existing;
    else {
      if (!existsSync(cached)) {
        const response = await fetch(url);
        if (!response.ok)
          throw new Error(`${song.id}: source HTTP ${response.status}`);
        writeFileSync(cached, Buffer.from(await response.arrayBuffer()));
      }
      source = cached;
    }
    const bytes = readFileSync(source);
    if (
      bytes.length !== song.audioIntegrity?.bytes ||
      createHash("sha256").update(bytes).digest("hex") !==
        song.audioIntegrity.sha256
    )
      throw new Error(`${song.id}: source checksum differs`);
  }
  const probe = spawnSync(
    "ffprobe",
    [
      "-v",
      "error",
      "-show_entries",
      "format=duration",
      "-of",
      "default=noprint_wrappers=1:nokey=1",
      source,
    ],
    { encoding: "utf8" },
  );
  const duration = Number(probe.stdout.trim());
  if (probe.status !== 0 || !Number.isFinite(duration) || duration <= 0)
    throw new Error(`${song.id}: cannot measure source duration`);
  const start = Math.max(
    0,
    Math.min(parseSimfile(data.ssc).sampleStart, duration - 20),
  );
  const temporary = join(staged, `${song.id}.mp3`);
  mkdirSync(dirname(temporary), { recursive: true });
  const result = spawnSync(
    "ffmpeg",
    [
      "-hide_banner",
      "-loglevel",
      "error",
      "-y",
      "-threads",
      "1",
      "-ss",
      String(start),
      "-i",
      source,
      "-vn",
      "-af",
      "atrim=duration=20,asetpts=PTS-STARTPTS,afade=t=in:st=0:d=0.08,afade=t=out:st=18.5:d=1.5,apad=whole_dur=22",
      "-t",
      "22",
      "-ar",
      "22050",
      "-ac",
      "2",
      "-c:a",
      "libmp3lame",
      "-b:a",
      "64k",
      "-map_metadata",
      "-1",
      temporary,
    ],
    { encoding: "utf8" },
  );
  if (result.status !== 0) throw new Error(`${song.id}: ${result.stderr}`);
  const bytes = readFileSync(temporary);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const object = `fusemania/previews/${song.id}/${sha256}.mp3`;
  const file = join(staged, object);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, bytes);
  // The temporary filename must not be uploaded alongside immutable object paths.
  unlinkSync(temporary);
  clips.push({
    id: song.id,
    url: `https://storage.googleapis.com/${bucket}/${object}`,
    bytes: bytes.length,
    sha256,
    start,
    audibleSeconds: 20,
    silenceSeconds: 2,
  });
  console.log(
    `preview ${song.id}: ${bytes.length} bytes, ${start.toFixed(2)}s source start`,
  );
}
writeFileSync(
  "games/fusemania/src/app/previews-data.ts",
  await format(
    `// Generated by scripts/fusemania-previews.ts. Audio lives in the public GCS media bucket, never Git.\nexport const PREVIEW_CLIPS = ${JSON.stringify(clips)} as const;\n`,
    { parser: "typescript" },
  ),
);
console.log(
  `Generated ${clips.length} previews: 20 seconds with fade, 2 seconds silence, 64kbps MP3.`,
);
