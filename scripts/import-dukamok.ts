/** Import the user's DukAmok Originals .sm/.dwi songs without regenerating their charts.
 * Usage: pnpm exec tsx scripts/import-dukamok.ts '/path/to/DukAmok Originals'
 * Requires ffmpeg for JPEG cover conversion. Prefer SM when both formats exist.
 */
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { basename, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { parseSimfile } from "../games/fusemania/src/engine/simfile.js";
import { createLibrary } from "../games/fusemania/src/engine/library.js";
import type { SongSpec } from "./lib/fusemania/songs.js";

process.chdir(fileURLToPath(new URL("..", import.meta.url)));
const source = process.argv[2];
if (!source) throw new Error("Pass the DukAmok Originals folder");
const pack = "dukamok-originals";
const charts = `games/fusemania/charts/${pack}`;
mkdirSync(charts, { recursive: true });
mkdirSync("public/music/covers", { recursive: true });
const songs: (SongSpec & { simfile: string })[] = [];
const deferred: string[] = [];
for (const entry of readdirSync(source, { withFileTypes: true }).sort((a, b) =>
  a.name.localeCompare(b.name, "en"),
)) {
  if (!entry.isDirectory()) continue;
  const folder = entry.name;
  const dir = join(resolve(source), folder);
  const files = readdirSync(dir);
  const simfile =
    files.find((file) => file.toLowerCase().endsWith(".sm")) ??
    files.find((file) => file.toLowerCase().endsWith(".dwi"));
  if (!simfile) {
    deferred.push(folder);
    continue;
  }
  const id = `dukamok-${folder
    .replace(/^\(DukAmok\)\s*/, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")}`;
  if (songs.some((song) => song.id === id))
    throw new Error(`Duplicate id: ${id}`);
  const text = readFileSync(join(dir, simfile), "utf8");
  const sim = parseSimfile(text);
  if (basename(sim.music) !== sim.music || !sim.music)
    throw new Error(`Unsafe audio name: ${sim.music}`);
  const media = readFileSync(join(dir, sim.music));
  const sha256 = createHash("sha256").update(media).digest("hex");
  const object = `fusemania/${pack}/${id}/${sha256}/${sim.music}`;
  const audio = `https://storage.googleapis.com/andershaf-87-fuse-media/${object.split("/").map(encodeURIComponent).join("/")}`;
  const library = createLibrary([{ id, audio, ssc: text }]);
  const loaded = library.song(id);
  const singles = sim.charts.filter(
    (chart) => chart.stepsType === "dance-single",
  );
  if (!loaded || loaded.charts.length !== singles.length)
    throw new Error(`Unplayable chart: ${folder}`);
  const original = `${charts}/${id}${simfile.toLowerCase().endsWith(".dwi") ? ".dwi" : ".sm"}`;
  // Staged for an explicit GCS sync; never put imported audio into public/ or Git.
  const staged = join("artifacts/dukamok-media", object);
  mkdirSync(join(staged, ".."), { recursive: true });
  copyFileSync(join(dir, sim.music), staged);
  copyFileSync(join(dir, simfile), original);
  const cover =
    files.find((file) => /-bg\.(png|jpg)$/i.test(file)) ??
    files.find((file) => /\.(png|jpg)$/i.test(file) && !file.startsWith("!"));
  if (!cover) throw new Error(`Missing cover: ${folder}`);
  const coverPath = `public/music/covers/${id}.jpg`;
  for (const quality of [3, 5, 7, 10, 15]) {
    const converted = spawnSync(
      "ffmpeg",
      [
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-i",
        join(dir, cover),
        "-vf",
        "scale=512:512:force_original_aspect_ratio=decrease,pad=512:512:(ow-iw)/2:(oh-ih)/2",
        "-frames:v",
        "1",
        "-q:v",
        String(quality),
        coverPath,
      ],
      { encoding: "utf8" },
    );
    if (converted.status !== 0) throw new Error(converted.stderr);
    if (statSync(coverPath).size < 120_000) break;
  }
  if (statSync(coverPath).size >= 120_000)
    throw new Error(`${id}: cover exceeds the carousel's size limit`);
  songs.push({
    id,
    title: sim.title,
    artist: sim.artist,
    audio,
    audioIntegrity: { bytes: media.length, sha256 },
    pack,
    simfile: original,
  });
}
writeFileSync(
  "scripts/lib/fusemania/dukamok-songs.ts",
  await format(
    `// Generated by scripts/import-dukamok.ts from the user's DukAmok Originals pack.\nexport const DUKAMOK_SONGS = ${JSON.stringify(songs)} as const;\n`,
    { parser: "typescript" },
  ),
);
console.log(
  `Imported ${songs.length} original SM/DWI songs. Deferred ${deferred.length} folders without a simfile:\n${deferred.join("\n")}`,
);
