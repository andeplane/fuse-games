export const FLEET_CAPACITY = 16;
export function listings(day: number): ModelId[] {
  const rotating = MODEL_IDS.slice(2),
    offset = (Math.floor((day - 1) / 7) * 7) % rotating.length;
  return [
    "kestrel",
    "marlin",
    ...Array.from(
      { length: 13 },
      (_, index) => rotating[(index + offset) % rotating.length]!,
    ),
  ];
}
