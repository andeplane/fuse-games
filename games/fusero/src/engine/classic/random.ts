export const fixedRandom = (index: number): number =>
  FIXED_RANDOM[index & 255]!;
/** Seeded replacement for platform rand(): the decision state is part of each world checkpoint. */
export function randomUnit(state: RandomState): number {
  state.rng = (Math.imul(state.rng, 1664525) + 1013904223) >>> 0;
  return Math.fround(state.rng / 4294967296);
}
export const randomSigned = (state: RandomState): number =>
  Math.fround(Math.fround(randomUnit(state) * 2) - 1);
/** Native GetRandomInt includes the maximum and rounds through float32 before truncation. */
export function randomInt(state: RandomState, max: number): number {
  return Math.max(
    0,
    Math.min(
      max,
      Math.trunc(Math.fround(randomUnit(state) * Math.fround(max + 1))),
    ),
  );
}
